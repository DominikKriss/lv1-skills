#!/usr/bin/env python3
"""Convert X32 scene channel processing to LV1 eMo F2 / Q4 / D5 settings (Markdown)."""
import math
import re
import sys

SKIP_FLAT = True


def hz(v):
    return float(v[:-3].replace("k", "") + "." + v[-2:]) * 1000 if "k" in v else float(v)


def fmt_hz(f):
    return f"{f / 1000:.2f} kHz" if f >= 1000 else f"{f:.0f} Hz"


def parse(path):
    ch = {}
    head = {}
    for line in open(path, encoding="latin-1"):
        t = line.split()
        if not t:
            continue
        m = re.match(r"/ch/(\d\d)/(.+)", t[0])
        if m:
            ch.setdefault(int(m.group(1)), {})[m.group(2)] = t[1:]
            continue
        m = re.match(r"/headamp/(\d{3})", t[0])
        if m:
            head[int(m.group(1))] = t[1:]
    name = {n: re.search(r'"([^"]*)"', open(path, encoding="latin-1").read().split(f"/ch/{n:02d}/config ")[1]).group(1) for n in ch}
    return ch, head, name


def key_filter(flt):
    on, typ, f = flt[0], flt[1], hz(flt[2])
    if on != "ON":
        return "-"
    if typ.startswith("LC"):
        return f"Key HPF {fmt_hz(f)}"
    if typ.startswith("HC"):
        return f"Key LPF {fmt_hz(f)}"
    q = float(typ)
    a = math.sqrt(1 + 1 / (4 * q * q))
    lo, hi = f * (a - 1 / (2 * q)), f * (a + 1 / (2 * q))
    return f"Key HPF {fmt_hz(lo)} / LPF {fmt_hz(hi)} (X32 BP {fmt_hz(f)} Q{q:g})"


def eq_rows(c):
    bands = [c[f"eq/{i}"] for i in range(1, 5)]
    pas_lo = [b for b in bands if b[0] == "LCut"]
    pas_hi = [b for b in bands if b[0] == "HCut"]
    rest = [b for b in bands if b[0] not in ("LCut", "HCut")]
    order = pas_lo + rest + pas_hi
    rows = []
    for i, b in enumerate(order, 1):
        typ, f, g, q = b[0], hz(b[1]), float(b[2]), float(b[3])
        if typ in ("PEQ", "VEQ"):
            if g == 0:
                rows.append(f"{i}: Off")
                continue
            t = "Bell" + (" (X32 VEQ)" if typ == "VEQ" else "")
        elif typ in ("LShv", "HShv"):
            if g == 0:
                rows.append(f"{i}: Off")
                continue
            t = "Shelf"
        else:
            rows.append(f"{i}: {'High' if typ == 'LCut' else 'Low'} Pass (12 dB/oct) {fmt_hz(f)}")
            continue
        rows.append(f"{i}: {t} {fmt_hz(f)} {g:+.2f} dB Q {q:.1f}")
    return rows


def knee(k):
    k = int(k)
    return "HARD" if k == 0 else "NORMAL" if k <= 2 else "SOFT"


def main(path):
    ch, head, name = parse(path)
    src = open(path, encoding="latin-1").read()
    routing_in = re.search(r"^/config/routing/IN (.+)$", src, re.M).group(1).split()
    out = [f"# LV1 eMo settings from `{path.split('/')[-1]}`", "",
           "Generated by `scenes/x32_to_emo.py`. Channels with no processing are left out.", "",
           "Mapping limits (X32 -> eMo):",
           "- Low cut: X32 24 dB/oct -> eMo F2 HP is 18 dB/oct.",
           "- EQ: PEQ/VEQ -> Bell, LShv/HShv -> Shelf, HCut/LCut -> Pass on band 4/1 (bands reordered so cuts land there). VEQ curves differ slightly; check by ear.",
           "- Comp knee: X32 0 -> HARD, 1-2 -> NORMAL, 3-5 -> SOFT. X32 PEAK/RMS and LIN/LOG have no D5 equivalent. Hold is dropped.",
           "- Gate: Floor = -range. Close threshold left at default. Release capped at 1000 ms.",
           "- X32 bandpass key filters -> D5 Key HPF/LPF at the -3 dB edges.",
           "- `dyn PRE EQ` = on the X32 the compressor ran before the EQ; set the same order in LV1 if the strip allows it.", ""]
    for n in sorted(ch):
        c = ch[n]
        trim, inv, hpon, _slope, hpf = c["preamp"][:5]
        eq_on = c["eq"][0] == "ON"
        eq = eq_rows(c) if eq_on else []
        g, d, df, gf = c["gate"], c["dyn"], c["dyn/filter"], c.get("gate/filter", ["OFF", "3.0", "1k00"])
        active = (eq and any("Off" not in r for r in eq)) or g[0] == "ON" or d[0] == "ON" or hpon == "ON"
        if SKIP_FLAT and not active:
            continue
        block = routing_in[(n - 1) // 8]
        out.append(f"## Ch {n} {name[n]}  (X32 source {block})")
        inp = [f"trim {trim} dB"]
        if block.startswith("AN"):
            h = head.get(n - 25, ["+0.0", "OFF"])
            inp.append(f"preamp gain {h[0]} dB, phantom {h[1]}")
        if inv == "ON":
            inp.append("**polarity invert ON**")
        out.append("- Input: " + ", ".join(inp))
        out.append(f"- F2: HP {'ON ' + hpf.strip() + ' Hz' if hpon == 'ON' else 'Off'}, LP Off")
        if eq_on and any("Off" not in r for r in eq):
            out.append("- Q4: " + " | ".join(eq))
        else:
            out.append("- Q4: Off")
        if g[0] == "ON":
            thr, rng, att, hold, rel = g[2], float(g[3]), float(g[4]), g[5], float(g[6])
            note = " (X32 release %s ms, clamped)" % g[6] if rel > 1000 else ""
            kf = key_filter(gf)
            out.append(f"- D5 Gate: ON, GATE, Open {thr} dB, Floor -{rng:g} dB, Attack {max(att, 0.1):g} ms, "
                       f"Hold {hold} ms, Release {min(rel, 1000):g} ms{note}" + (f", {kf}" if kf != "-" else ""))
        else:
            out.append("- D5 Gate: Off")
        if d[0] == "ON":
            _on, mode, det, env, thr, ratio, kn, mg, att, _hold, rel, pos, _ks, mix = d[:14]
            r = float(ratio)
            rtxt = f"{min(r, 20):g}" + (" (X32 %g:1, consider Limiter at %s dB instead)" % (r, thr) if r > 20 else "")
            parts = [f"Threshold {thr} dB", f"Ratio {rtxt}", f"Knee {knee(kn)} (X32 {kn})",
                     f"Attack {max(float(att), 0.5):g} ms", f"Release {float(rel):g} ms (MANUAL)",
                     f"Makeup {float(mg):+g} dB"]
            if int(mix) != 100:
                parts.append(f"Comp Mix {mix}")
            kf = key_filter(df)
            if kf != "-":
                parts.append(kf)
            out.append(f"- D5 Comp: ON, " + ", ".join(parts) + f"  [X32 {det}/{env}, dyn {pos} EQ]")
        else:
            out.append("- D5 Comp: Off")
        out.append("")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
