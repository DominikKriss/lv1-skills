#!/usr/bin/env python3
"""Convert X32 scene channel processing to LV1 eMo F2 / Q4 / D5 settings (Markdown)."""
import itertools
import math
import re
import sys

SKIP_FLAT = True
SLOT_TYPES = {1: {"Bell", "LowShelf", "HighPass"}, 2: {"Bell", "LowShelf"},
              3: {"Bell", "HighShelf"}, 4: {"Bell", "HighShelf", "LowPass"}}


def hz(v):
    return float(v[:-3].replace("k", "") + "." + v[-2:]) * 1000 if "k" in v else float(v)


def fmt_hz(f):
    return f"{f / 1000:.2f} kHz" if f >= 1000 else f"{f:.0f} Hz"


def parse(path):
    ch = {}
    head = {}
    for line in open(path, encoding="latin-1"):
        t = line.split()
        if not t:
            continue
        m = re.match(r"/ch/(\d\d)/(.+)", t[0])
        if m:
            ch.setdefault(int(m.group(1)), {})[m.group(2)] = t[1:]
            continue
        m = re.match(r"/headamp/(\d{3})", t[0])
        if m:
            head[int(m.group(1))] = t[1:]
    name = {n: re.search(r'"([^"]*)"', open(path, encoding="latin-1").read().split(f"/ch/{n:02d}/config ")[1]).group(1) for n in ch}
    return ch, head, name


def place_eq(bands):
    """Assign X32 EQ bands to Q4 slots 1-4 within the per-slot type limits, keeping frequency order."""
    kinds = []
    for typ, f, g, q in bands:
        kind = {"PEQ": "Bell", "VEQ": "Bell", "LShv": "LowShelf", "HShv": "HighShelf",
                "LCut": "HighPass", "HCut": "LowPass"}[typ]
        if kind in ("Bell", "LowShelf", "HighShelf") and g == 0:
            continue
        kinds.append((kind, f, g, q))
    best, dropped = None, []
    for perm in itertools.permutations(range(1, 5), len(kinds)):
        if all(k[0] in SLOT_TYPES[s] for k, s in zip(kinds, perm)):
            inv = sum(1 for (a, sa), (b, sb) in itertools.combinations(zip(kinds, perm), 2)
                      if (a[1] - b[1]) * (sa - sb) < 0)
            if best is None or inv < best[0]:
                best = (inv, perm)
    if best is None:
        kinds = sorted(kinds, key=lambda k: abs(k[2]) if k[0] != "HighPass" else 99, reverse=True)
        while kinds and best is None:
            dropped.append(kinds.pop())
            for perm in itertools.permutations(range(1, 5), len(kinds)):
                if all(k[0] in SLOT_TYPES[s] for k, s in zip(kinds, perm)):
                    best = (0, perm)
                    break
    return {s: k for k, s in zip(kinds, best[1] if best else ())}, dropped


def key_filter(flt):
    on, typ, f = flt[0], flt[1], hz(flt[2])
    if on != "ON":
        return "-"
    if typ.startswith("LC"):
        return f"Key HPF {fmt_hz(f)}"
    if typ.startswith("HC"):
        return f"Key LPF {fmt_hz(f)}"
    q = float(typ)
    a = math.sqrt(1 + 1 / (4 * q * q))
    lo, hi = f * (a - 1 / (2 * q)), f * (a + 1 / (2 * q))
    return f"Key HPF {fmt_hz(lo)} / LPF {fmt_hz(hi)} (X32 BP {fmt_hz(f)} Q{q:g})"


def eq_rows(c):
    """Q4 bands as the preset writer places them (slot limits, flat bands off, dropped bands listed)."""
    bands = [(b[0], hz(b[1]), float(b[2]), float(b[3])) for b in (c[f"eq/{i}"] for i in range(1, 5))]
    slots, dropped = place_eq(bands)
    veq = {(f, g) for typ, f, g, _q in bands if typ == "VEQ"}
    label = {"Bell": "Bell", "LowShelf": "Low Shelf", "HighShelf": "High Shelf"}
    rows = []
    for slot in range(1, 5):
        if slot not in slots:
            rows.append(f"{slot}: Off")
            continue
        kind, f, g, q = slots[slot]
        if kind in ("HighPass", "LowPass"):
            rows.append(f"{slot}: {'High' if kind == 'HighPass' else 'Low'} Pass (12 dB/oct) {fmt_hz(f)}")
        else:
            vtag = " (X32 VEQ)" if kind == "Bell" and (f, g) in veq else ""
            rows.append(f"{slot}: {label[kind]}{vtag} {fmt_hz(f)} {g:+.2f} dB Q {q:.1f}")
    rows += [f"dropped: {k} {fmt_hz(f)}" for k, f, _g, _q in dropped]
    return rows


def knee(k):
    k = int(k)
    return "HARD" if k == 0 else "NORMAL" if k <= 2 else "SOFT"


def main(path):
    ch, head, name = parse(path)
    src = open(path, encoding="latin-1").read()
    routing_in = re.search(r"^/config/routing/IN (.+)$", src, re.M).group(1).split()
    out = [f"# LV1 eMo settings from `{path.split('/')[-1]}`", "",
           "Generated by `scenes/x32_to_emo.py`. Channels with no processing are left out.", "",
           "Mapping limits (X32 -> eMo):",
           "- Low cut: X32 24 dB/oct -> eMo F2 HP is 18 dB/oct.",
           "- EQ: PEQ/VEQ -> Bell, LShv/HShv -> Shelf, LCut/HCut -> Pass, placed in the Q4 bands that allow each type, in frequency order. VEQ curves differ slightly; check by ear.",
           "- Comp knee: X32 0 -> HARD, 1-2 -> NORMAL, 3-5 -> SOFT. X32 PEAK/RMS and LIN/LOG have no D5 equivalent. Hold is dropped. Only COMP mode is converted (EXP isn't).",
           "- Gate: only GATE mode is converted (EXP2-4 and DUCK aren't).",
           "- Gate: Floor = -range. Close threshold left at default. Release capped at 1000 ms.",
           "- X32 bandpass key filters -> D5 Key HPF/LPF at the -3 dB edges.",
           "- `dyn PRE EQ` = on the X32 the compressor ran before the EQ; set the same order in LV1 if the strip allows it.", ""]
    for n in sorted(ch):
        c = ch[n]
        trim, inv, hpon, _slope, hpf = c["preamp"][:5]
        eq_on = c["eq"][0] == "ON"
        eq = eq_rows(c) if eq_on else []
        g, d, df, gf = c["gate"], c["dyn"], c["dyn/filter"], c.get("gate/filter", ["OFF", "3.0", "1k00"])
        active = ((eq and any("Off" not in r for r in eq)) or g[0] == "ON" or d[0] == "ON" or hpon == "ON"
                  or float(trim) != 0 or inv == "ON")
        if SKIP_FLAT and not active:
            continue
        source = int(c["config"][-1])
        block = routing_in[(source - 1) // 8] if 1 <= source <= 32 else f"source {source}"
        out.append(f"## Ch {n} {name[n]}  (X32 source {block})")
        inp = [f"trim {trim} dB"]
        local = re.match(r"AN(\d+)-", block)
        if local:
            h = head.get(int(local.group(1)) - 1 + (source - 1) % 8, ["+0.0", "OFF"])
            inp.append(f"preamp gain {h[0]} dB, phantom {h[1]}")
        if inv == "ON":
            inp.append("**polarity invert ON**")
        out.append("- Input: " + ", ".join(inp))
        out.append(f"- F2: HP {'ON ' + hpf.strip() + ' Hz' if hpon == 'ON' else 'Off'}, LP Off")
        if eq_on and any("Off" not in r for r in eq):
            out.append("- Q4: " + " | ".join(eq))
        else:
            out.append("- Q4: Off")
        if g[0] == "ON" and g[1] != "GATE":
            out.append(f"- D5 Gate: Off (X32 gate mode {g[1]} not converted)")
        elif g[0] == "ON":
            thr, rng, att, hold, rel = g[2], float(g[3]), float(g[4]), g[5], float(g[6])
            note = " (X32 release %s ms, clamped)" % g[6] if rel > 1000 else ""
            kf = key_filter(gf)
            out.append(f"- D5 Gate: ON, GATE, Open {thr} dB, Floor -{rng:g} dB, Attack {max(att, 0.1):g} ms, "
                       f"Hold {hold} ms, Release {min(rel, 1000):g} ms{note}" + (f", {kf}" if kf != "-" else ""))
        else:
            out.append("- D5 Gate: Off")
        if d[0] == "ON" and d[1] != "COMP":
            out.append(f"- D5 Comp: Off (X32 dynamics mode {d[1]} not converted)")
        elif d[0] == "ON":
            _on, mode, det, env, thr, ratio, kn, mg, att, _hold, rel, pos, _ks, mix = d[:14]
            r = float(ratio)
            rtxt = f"{min(r, 20):g}" + (" (X32 %g:1, consider Limiter at %s dB instead)" % (r, thr) if r > 20 else "")
            parts = [f"Threshold {thr} dB", f"Ratio {rtxt}", f"Knee {knee(kn)} (X32 {kn})",
                     f"Attack {max(float(att), 0.5):g} ms", f"Release {float(rel):g} ms (MANUAL)",
                     f"Makeup {float(mg):+g} dB"]
            if int(mix) != 100:
                parts.append(f"Comp Mix {mix}")
            kf = key_filter(df)
            if kf != "-":
                parts.append(kf)
            out.append(f"- D5 Comp: ON, " + ", ".join(parts) + f"  [X32 {det}/{env}, dyn {pos} EQ]")
        else:
            out.append("- D5 Comp: Off")
        out.append("")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
